  // Current active language (DEFAULT: ENGLISH)
  currentLang: 'en',

  /**
   * Initialize i18n with English as default
   */
  init(defaultLang = 'en') {
    const saved = localStorage.getItem('dosespeak_language');
    this.currentLang = saved && this.languages.some(l => l.code === saved) ? saved : defaultLang;
    this.applyLanguage(this.currentLang);
  },

  /**
   * Translate a key into target language
   */
  t(key, lang = null) {
    const target = lang || this.currentLang;
    const entry = this.dict[key];
    if (!entry) return key;
    return entry[target] || entry['en'] || key;
  },

  /**
   * Set and apply language
   */
  setLanguage(langCode) {
    if (!this.languages.some(l => l.code === langCode)) return;
    this.currentLang = langCode;
    localStorage.setItem('dosespeak_language', langCode);
    this.applyLanguage(langCode);
  },

  /**
   * Apply language to DOM
   */
  applyLanguage(langCode) {
    document.documentElement.lang = langCode;

    // Translate all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      const translated = this.t(key, langCode);
      if (translated) {
        el.textContent = translated;
      }
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.dataset.i18nPlaceholder;
      const translated = this.t(key, langCode);
      if (translated) {
        el.placeholder = translated;
      }
    });

    // Translate aria-labels
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.dataset.i18nAria;
      const translated = this.t(key, langCode);
      if (translated) {
        el.setAttribute('aria-label', translated);
      }
    });

    // Sync all dropdowns and select elements
    document.querySelectorAll('select.lang-dropdown, #global-lang-select, #a11y-lang-select, #mobile-lang-select, #result-lang-select').forEach(sel => {
      if (sel.value !== langCode) {
        sel.value = langCode;
      }
    });

    // Update active state on any button links
    document.querySelectorAll('.lang-btn[data-lang], .lang-picker-item[data-lang], .footer-lang-link[data-lang]').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === langCode);
    });

    // Trigger event for listeners
    window.dispatchEvent(new CustomEvent('dosespeak:languageChanged', { detail: { lang: langCode } }));
  }
